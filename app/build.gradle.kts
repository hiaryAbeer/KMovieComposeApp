// The TMDB key is read from local.properties (git-ignored) or, on CI, from the
// TMDB_API_KEY environment variable. It is never stored in source control.
val tmdbApiKey: String =
    Properties()
        .apply {
            rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use(::load)
        }.getProperty("TMDB_API_KEY")
        ?: System.getenv("TMDB_API_KEY")
        ?: "".also { logger.warn("TMDB_API_KEY is not set: add it to local.properties (see README).") }

